CREATE OR REPLACE FUNCTION public.create_profile_for_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    student_id TEXT;
    student_row RECORD;
BEGIN
    student_id := SUBSTRING(NEW.email FROM '^student[.]([0-9]{10})@id-life[.]invalid$');

    IF student_id IS NULL THEN
        RAISE EXCEPTION 'Student account alias is invalid';
    END IF;

    SELECT
        s.student_prefix,
        s.student_first_name,
        s.student_last_name,
        s.student_birth
    INTO student_row
    FROM public.students AS s
    WHERE s.student_id::TEXT = student_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Student ID is not registered';
    END IF;

    INSERT INTO public.profiles (
        id,
        public_id,
        student_prefix,
        first_name,
        last_name,
        dob
    )
    VALUES (
        NEW.id,
        student_id,
        COALESCE(student_row.student_prefix, ''),
        COALESCE(student_row.student_first_name, ''),
        COALESCE(student_row.student_last_name, ''),
        student_row.student_birth::DATE
    );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created_profile ON auth.users;
CREATE TRIGGER on_auth_user_created_profile
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.create_profile_for_new_user();

