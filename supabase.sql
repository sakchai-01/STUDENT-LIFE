CREATE OR REPLACE FUNCTION public.record_student_login_attempt(
    p_student_id TEXT,
    p_ip_hash TEXT
)
RETURNS TABLE (allowed BOOLEAN, retry_after_seconds INTEGER)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    current_attempts INTEGER;
    current_window TIMESTAMPTZ;
BEGIN
    INSERT INTO public.student_login_attempts AS attempt (
        student_id,
        ip_hash,
        window_started_at,
        attempt_count
    )
    VALUES (p_student_id, p_ip_hash, NOW(), 1)
    ON CONFLICT (student_id, ip_hash) DO UPDATE
    SET window_started_at = CASE
            WHEN attempt.window_started_at <= NOW() - INTERVAL '15 minutes'
                THEN NOW()
            ELSE attempt.window_started_at
        END,
        attempt_count = CASE
            WHEN attempt.window_started_at <= NOW() - INTERVAL '15 minutes'
                THEN 1
            ELSE attempt.attempt_count + 1
        END
    RETURNING attempt.attempt_count, attempt.window_started_at
    INTO current_attempts, current_window;

    RETURN QUERY
    SELECT
        current_attempts <= 8,
        GREATEST(
            0,
            CEIL(EXTRACT(EPOCH FROM (
                current_window + INTERVAL '15 minutes' - NOW()
            )))::INTEGER
        );
END;
$$;

REVOKE ALL ON FUNCTION public.record_student_login_attempt(TEXT, TEXT)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_student_login_attempt(TEXT, TEXT)
    TO service_role;

